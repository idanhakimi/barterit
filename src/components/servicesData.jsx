// Helper functions
export const getAllCategories = () => Object.keys(serviceCategories);

export const getServicesForCategory = (category) => serviceCategories[category] || [];

export const getAllServices = () => {
  return Object.values(serviceCategories).flat();
};

export const findCategoryForService = (service) => {
  for (const [category, services] of Object.entries(serviceCategories)) {
    if (services.includes(service)) {
      return category;
    }
  }
  return null;
};

export const searchServices = (query) => {
  if (!query) return [];
  
  const results = [];
  const lowerQuery = query.toLowerCase();
  
  Object.entries(serviceCategories).forEach(([category, services]) => {
    services.forEach(service => {
      if (service.toLowerCase().includes(lowerQuery)) {
        results.push({ category, service });
      }
    });
    
    // Also search in category names
    if (category.toLowerCase().includes(lowerQuery)) {
      services.forEach(service => {
        // Prevent duplicates if a service is in a category that also matches the query
        if (!results.find(r => r.service === service)) {
          results.push({ category, service });
        }
      });
    }
  });
  
  return results;
};